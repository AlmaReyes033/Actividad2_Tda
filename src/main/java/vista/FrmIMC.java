    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {

        // Obtener datos del formulario
        String nombre = txtNombre.getText().trim();

        double peso = Double.parseDouble(
                txtPeso.getText().trim()
        );

        double estatura = Double.parseDouble(
                txtEstatura.getText().trim()
        );

        // Crear objeto del TDA mediante herencia
        IMCAdulto persona = new IMCAdulto(
                nombre,
                peso,
                estatura
        );

        // Utilizar los métodos del TDA
        double imc =
                persona.obtenerIMCRedondeado();

        String categoria =
                persona.obtenerCategoria();

        String pesoSaludable =
                persona.calcularPesoSaludable();

        String recomendacion =
                persona.obtenerRecomendacion();

        // Mostrar resultados
        lblResultado.setText(
                "IMC: " + imc
        );

        lblCategoria.setText(
                "Categoría: " + categoria
        );

        lblPesoSaludable.setText(
                "Peso saludable: " + pesoSaludable
        );

        lblRecomendacion.setText(
                "<html>Recomendación: "
                + recomendacion
                + "</html>"
        );

        // Mostrar resumen
        lblResumen.setText(
                "<html>"
                + persona.generarResumen()
                        .replace("\n", "<br>")
                + "</html>"
        );

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Ingresa valores numéricos válidos "
                + "para peso y estatura.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );

    } catch (IllegalArgumentException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnCalcularActionPerformed

